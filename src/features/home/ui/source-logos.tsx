/** Trang media của một tên miền (kể cả tên miền con như m.youtube.com), không có thì undefined. */
export function mediaSourceOf(host: string): MediaSource | undefined {
  const value = host
    .trim()
    .toLowerCase()
    .replace(/^www\./, "")
  if (!value) return undefined
  return MEDIA_SOURCES.find((source) =>
    source.hosts.some(
      (domain) => value === domain || value.endsWith(`.${domain}`)
    )
  )
}

/** Logo một trang; mặc định chỉ để trang trí (aria-hidden), truyền `label` khi logo đứng một mình. */
export function SourceLogo({
  source,
  label,
  className,
}: {
  source: MediaSource
  label?: string
  className?: string
}) {
  return (
    <svg
      viewBox="0 0 24 24"
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      fill={source.color}
      className={cn("size-4 shrink-0", className)}
    >
      <path d={source.path} />
    </svg>
  )
}
